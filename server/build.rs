//! Compile-time embedding of the UI: scans `../ui/dist` (if present) and emits
//! a static asset table with `include_bytes!`. Keeps the server a single
//! binary with zero runtime file dependencies. Missing `ui/dist` is fine:
//! the embedded UI will be an empty table (API-only mode).

use std::{env, fs, path::PathBuf};

fn mime_for(ext: &str) -> &'static str {
    match ext {
        "html" => "text/html; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "json" | "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "txt" => "text/plain; charset=utf-8",
        "webmanifest" => "application/manifest+json",
        _ => "application/octet-stream",
    }
}

fn walk(dir: &PathBuf, base: &str, out: &mut Vec<(String, String, String)>) {
    let entries = match fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return,
    };
    let mut subs: Vec<PathBuf> = entries.filter_map(|e| e.ok()).map(|e| e.path()).collect();
    subs.sort();
    for p in subs {
        if p.is_dir() {
            walk(&p, base, out);
        } else {
            let abs = p.display().to_string();
            let mut rel_from_base = abs[base.len()..].to_string();
            while rel_from_base.starts_with('/') {
                rel_from_base.remove(0);
            }
            if rel_from_base.is_empty() {
                continue;
            }
            let ext = rel_from_base.rsplit('.').next().unwrap_or("").to_string();
            out.push((rel_from_base, mime_for(&ext).to_string(), abs));
        }
    }
}

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let dist = manifest_dir.join("../ui/dist");
    println!("cargo:rerun-if-changed={}", dist.display());

    let mut assets: Vec<(String, String, String)> = Vec::new();
    let base = dist.display().to_string();
    walk(&dist, &base, &mut assets);
    assets.sort();

    let mut gen = String::new();
    gen.push_str("// generated by build.rs — do not edit\n");
    gen.push_str("pub(crate) struct Asset { pub(crate) path: &'static str, pub(crate) mime: &'static str, pub(crate) bytes: &'static [u8] }\n");
    gen.push_str("pub(crate) static ASSETS: &[Asset] = &[\n");
    for (path, mime, abs) in &assets {
        gen.push_str(&format!(
            "    Asset {{ path: {path:?}, mime: {mime:?}, bytes: include_bytes!({abs:?}) }},\n"
        ));
    }
    gen.push_str("];\n");
    fs::write(out_dir.join("ui_assets.rs"), gen).unwrap();
}